#!/usr/bin/env python3
"""Render tokens/tokens.json into theme files.

Currently generates:
  color-schemes/PlatinumNeueLight.colors
  color-schemes/PlatinumNeueDark.colors

Usage: python3 tools/gen.py [--check]
  --check  also print WCAG contrast ratios for the key pairs and exit non-zero on failure
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "tokens" / "tokens.json").read_text())


# ---------- colour helpers ----------
def rgb(hex_):
    h = hex_.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a, b, t):
    """Mix hex a toward hex b by t (0..1), in sRGB. Returns hex."""
    ca, cb = rgb(a), rgb(b)
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(ca, cb))


def kde(hex_):
    return ",".join(str(c) for c in rgb(hex_))


def lum(hex_):
    def ch(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(c) for c in rgb(hex_))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


# ---------- colour scheme ----------
def group(bg, bg_alt, fg, fg_inactive, t, acc, *, fg_active=None, link=None):
    return {
        "BackgroundNormal": bg,
        "BackgroundAlternate": bg_alt,
        "ForegroundNormal": fg,
        "ForegroundInactive": fg_inactive,
        "ForegroundActive": fg_active or acc["accent"],
        "ForegroundLink": link or t["link"],
        "ForegroundVisited": t["visited"],
        "ForegroundNegative": t["negative"],
        "ForegroundNeutral": t["neutral"],
        "ForegroundPositive": t["positive"],
        "DecorationFocus": acc["focus"],
        "DecorationHover": acc["accent"],
    }


def scheme(mode):
    t = TOKENS["modes"][mode]
    other = TOKENS["modes"]["dark" if mode == "light" else "light"]
    a = TOKENS["accents"][TOKENS["accents"]["default"]]
    acc = {
        "accent": a[mode],
        "on": a["onLight" if mode == "light" else "onDark"],
        "focus": a["focusLight" if mode == "light" else "focusDark"],
    }
    dark = TOKENS["modes"]["dark"]

    groups = {
        "Colors:Window": group(t["chrome"], t["chrome2"], t["text"], t["text2"], t, acc),
        "Colors:View": group(t["content"], t["contentAlt"], t["text"], t["text2"], t, acc),
        "Colors:Button": group(t["raised"], t["chrome2"], t["text"], t["text2"], t, acc),
        "Colors:Header": group(t["chrome"], t["chrome2"], t["text"], t["text2"], t, acc),
        "Colors:Header][Inactive": group(t["chrome"], t["chrome2"], t["text2"], t["text2"], t, acc),
        "Colors:Selection": group(
            acc["accent"], mix(acc["accent"], t["content"], 0.6), acc["on"], acc["on"], t, acc,
            fg_active=acc["on"], link=acc["on"]),
        "Colors:Tooltip": group(
            t["tipBg"], mix(t["tipBg"], t["tipFg"], 0.1), t["tipFg"], mix(t["tipFg"], t["tipBg"], 0.35),
            other, acc, link=other["link"]),
        # Complementary = the always-dark surfaces (lock screen, OSDs) in both modes.
        "Colors:Complementary": group(
            mix(dark["chrome"], "#000000", 0.15 if mode == "dark" else 0), dark["chrome2"],
            dark["text"], dark["text2"], dark, acc, link=dark["link"]),
    }

    out = [
        "# Generated by tools/gen.py from tokens/tokens.json. Do not edit by hand.",
        "",
        "[ColorEffects:Disabled]",
        "Color=56,56,56", "ColorAmount=0", "ColorEffect=0",
        "ContrastAmount=0.65", "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2",
        "",
        "[ColorEffects:Inactive]",
        "ChangeSelectionColor=true", "Color=112,111,110", "ColorAmount=0.025", "ColorEffect=2",
        "ContrastAmount=0.1", "ContrastEffect=2", "Enable=false", "IntensityAmount=0", "IntensityEffect=0",
        "",
    ]
    for name, keys in groups.items():
        out.append(f"[{name}]")
        out += [f"{k}={kde(v)}" for k, v in sorted(keys.items())]
        out.append("")

    sid = f"{TOKENS['id']}{mode.capitalize()}"
    out += [
        "[General]",
        f"ColorScheme={sid}",
        f"Name={TOKENS['name']} {mode.capitalize()}",
        "shadeSortColumn=true",
        "",
        "[KDE]",
        "contrast=4",
        "",
        "[WM]",
        f"activeBackground={kde(t['chrome'])}",
        f"activeBlend={kde(t['chrome'])}",
        f"activeForeground={kde(t['text'])}",
        f"inactiveBackground={kde(t['chrome'])}",
        f"inactiveBlend={kde(t['chrome'])}",
        f"inactiveForeground={kde(t['text2'])}",
        "",
    ]
    return sid, "\n".join(out)


# ---------- contrast check ----------
def check():
    ok = True
    for mode, t in TOKENS["modes"].items():
        print(f"\n{mode}")
        pairs = [
            ("text", "content", 7), ("text", "chrome", 7), ("text", "raised", 7),
            ("text2", "chrome", 4.5), ("text2", "content", 4.5),
            ("line", "chrome", 3), ("line", "content", 3),
            ("tipFg", "tipBg", 7),
            ("link", "content", 4.5), ("negative", "content", 4.5),
            ("neutral", "content", 4.5), ("positive", "content", 4.5),
        ]
        for f, b, target in pairs:
            r = contrast(t[f], t[b])
            flag = "ok  " if r >= target else "FAIL"
            ok &= r >= target
            print(f"  {flag} {f:>9} on {b:<8} {r:5.2f}:1  (≥{target})")
        for name, a in TOKENS["accents"].items():
            if name == "default":
                continue
            bg, on = a[mode], a["onLight" if mode == "light" else "onDark"]
            focus = a["focusLight" if mode == "light" else "focusDark"]
            r1, r2 = contrast(on, bg), contrast(focus, t["chrome"])
            good = r1 >= 4.5 and r2 >= 3
            ok &= good
            print(f"  {'ok  ' if good else 'FAIL'} accent {name:<9} text {r1:4.2f}:1  focus {r2:4.2f}:1")
    return ok


def main():
    outdir = ROOT / "color-schemes"
    outdir.mkdir(exist_ok=True)
    for mode in ("light", "dark"):
        sid, text = scheme(mode)
        (outdir / f"{sid}.colors").write_text(text)
        print(f"wrote color-schemes/{sid}.colors")
    if "--check" in sys.argv and not check():
        sys.exit(1)


if __name__ == "__main__":
    main()
